const catalogs: Record<Locale, Record<MessageKey, string>> = { en, ja }

export function translate(
  locale: Locale,
  key: MessageKey,
  params: MessageParams = {},
): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? `{${name}}`),
  )
}

export interface UiMessage {
  key: MessageKey
  params?: MessageParams
}

export function changeSetOperationCountMessage(count: number): UiMessage {
  return {
    key: count === 1 ? 'changes.countOne' : 'changes.countMany',
    params: { count },
  }
}

