function inline(
  component: Omit<Extract<ScreenComponent, { nodeType: 'inline' }>, 'nodeType' | 'sizing'> & {
    sizing?: Extract<ScreenComponent, { nodeType: 'inline' }>['sizing']
  },
): Extract<ScreenComponent, { nodeType: 'inline' }> {
  return {
    nodeType: 'inline',
    sizing: component.parentId === null
      ? { ...ROOT_COMPONENT_SIZING }
      : component.sizing
        ? { ...component.sizing }
        : { ...DEFAULT_COMPONENT_SIZING },
    ...component,
  }
}

function definitionInstance(
  component: Omit<Extract<ScreenComponent, { nodeType: 'definitionInstance' }>, 'nodeType' | 'childIds'>,
): Extract<ScreenComponent, { nodeType: 'definitionInstance' }> {
  return {
    nodeType: 'definitionInstance',
    childIds: [],
    ...component,
  }
}

function scenario(
  value: ScreenScenario,
): ScreenState {
  return value
}

